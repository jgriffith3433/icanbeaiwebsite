// docs/playtests.md is generated from the scenario list in js/playtest.js (id, budget `seconds`, phone, tags, what it
// plays, what it measures). `node scripts/sync-playtests.mjs` rewrites it; `--check` (in npm test) fails when:
//   - a scenario has no title, no description or no budget (`seconds` > 0),
//   - an id is listed twice, or listed with no runner (`id === "x"` dispatch), or has two runners,
//   - a runner has no list entry (a scenario Studio can't see),
//   - docs/playtests.md is stale.
import fs from "node:fs";
import vm from "node:vm";

const SRC = "js/playtest.js";
const DOC = "docs/playtests.md";
const src = fs.readFileSync(SRC, "utf8");

const a = src.indexOf("\n  scenarios: [");
const b = src.indexOf("\n  ],\n", a);
if (a < 0 || b < 0) { console.error("sync-playtests: scenarios list not found in " + SRC); process.exit(1); }
const list = vm.runInNewContext("(" + src.slice(a + 14, b + 4) + ")");

const problems = [];
const ids = list.map((s) => s.id);
for (const s of list) {
  if (!s.id) { problems.push("a scenario has no id"); continue; }
  if (!s.title) problems.push(`${s.id}: no title`);
  if (!s.description) problems.push(`${s.id}: no description`);
  if (!(Number(s.seconds) > 0)) problems.push(`${s.id}: no budget (seconds)`);
  if (ids.indexOf(s.id) !== list.indexOf(s)) problems.push(`${s.id}: listed twice`);
}
const runners = [...src.matchAll(/else if \(id === "([^"]+)"\) await \w+\(options, t\);/g)].map((m) => m[1]);
for (const id of ids) {
  const n = runners.filter((r) => r === id).length;
  if (n === 0) problems.push(`${id}: listed, but nothing runs it`);
  if (n > 1) problems.push(`${id}: ${n} runners (one wins, the rest are dead)`);
}
for (const r of new Set(runners)) if (!ids.includes(r)) problems.push(`${r}: has a runner but is not in the list`);

const cell = (x) => String(x).replace(/\|/g, "\\|").replace(/\n/g, " ");
function measures(d) {
  const ev = d.match(/Events ([^.;]*?)(?:;|\. |\.$|$)/);
  const me = d.match(/[Mm]etrics? ([^.]*?)(?:\. |\.$|$)/);
  const out = [];
  if (ev) out.push("events " + ev[1].trim());
  if (me) out.push("metrics " + me[1].trim());
  return out.length ? out.join("; ") : "see what it plays (no named events or metrics)";
}
const rows = list.map((s) => {
  const tags = s.tags || [];
  return `| \`${s.id}\` | ${s.seconds} s | ${tags.includes("phone") ? "yes" : ""} | ${tags.join(", ")} | ${cell(s.title)} | ${cell(measures(s.description || ""))} |`;
});
const totalSec = list.reduce((n, s) => n + (Number(s.seconds) || 0), 0);
const doc = `# Playtest scenarios

Generated by \`node scripts/sync-playtests.mjs\` from the \`scenarios\` list in \`js/playtest.js\`: do not edit by hand.
\`npm test\` runs \`--check\`, which fails when a scenario lacks a title, description or budget, is listed twice, has no
runner (or two), a runner is not listed, or this file is stale. Load one with \`?playtest=<id>\`.

${list.length} scenarios, ${list.filter((s) => (s.tags || []).includes("phone")).length} marked phone, budgets add up to ${Math.round(totalSec / 60)} min.
**Budget** is the scenario's time allowance in seconds. **Phone** means it also runs at 390x844 touch
(\`{"touch":true}\`), played by taps and drags only. **Measures** is what its description names: the events it puts on the
timeline and the metrics it reports. The full description of each is in \`js/playtest.js\`.

| Scenario | Budget | Phone | Tags | What it plays | Measures |
|---|---|---|---|---|---|
${rows.join("\n")}
`;

if (process.argv.includes("--check")) {
  if (!fs.existsSync(DOC) || fs.readFileSync(DOC, "utf8") !== doc) problems.push(`${DOC} is stale: run node scripts/sync-playtests.mjs`);
  if (problems.length) { console.error("check-playtests FAILED:\n - " + problems.join("\n - ")); process.exit(1); }
  console.log(`check-playtests ok: ${list.length} scenarios, all with description and budget`);
} else {
  if (problems.length) { console.error("sync-playtests problems:\n - " + problems.join("\n - ")); process.exit(1); }
  fs.writeFileSync(DOC, doc);
  console.log(`wrote ${DOC}: ${list.length} scenarios`);
}
